"""Item icons -> src/shared/gen/Icons.luau: the web silhouettes (src/ui/icons.ts, rasterized by tools/gen_icons.mjs to
data/icon_masks.json as 64x64 alpha+luminance) and, per shipped item, its shape (icons.ts shapeFor) and tint (the item
colour + 70 per channel, icons.ts lighten).  Usage: python3 tools/gen_icons.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from luastr import luastr
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
masks = json.load(open(os.path.join(ROOT, 'data/icon_masks.json')))
src = open(os.path.join(ROOT, 'src/shared/gen/Items.luau')).read()
# the shipped item rows: id, kind, cat, name, color, fire caliber / pellets / mag
items = {}
head = src[:src.find('M.gunFeel')]
starts = [m.start() for m in re.finditer(r'\{id="[^"]+",name="', head)]
for i, st in enumerate(starts):
    row = head[st:starts[i + 1] if i + 1 < len(starts) else len(head)]
    mid = re.match(r'\{id="([^"]+)",name="((?:[^"\\]|\\.)*)",kind="(\w+)",cat="(\w*)"', row)
    if not mid:
        continue
    iid, name, kind, cat = mid.groups()
    col = re.search(r'color="(#[0-9a-fA-F]{6})"', row)
    fire = re.search(r'fire=\{([^}]*)\}', row)
    f = {}
    if fire:
        for k, v in re.findall(r'(\w+)=("?[^,"]*"?)', fire.group(1)):
            f[k] = v.strip('"')
    items[iid] = dict(name=name, kind=kind, cat=cat, color=col.group(1) if col else '#888888', fire=f)
CAT_SHAPE = {'Attachment': 'attachment', 'Electronics': 'chip', 'Blueprint': 'blueprint', 'Information': 'document', 'Quest': 'document',
             'Daily': 'daily', 'Container': 'box', 'Tool': 'tool', 'Material': 'material', 'Valuable': 'valuable', 'Explosive': 'grenade',
             'Key': 'key', 'Totem': 'totem', 'Mask': 'face', 'Medicine': 'med', 'Ammo': 'ammo', 'Food': 'food', 'Drink': 'drink',
             'Armor': 'armor', 'Helmet': 'helmet', 'Headset': 'headset', 'Backpack': 'backpack'}
BLUNT = re.compile(r'stick|baton|bat\b|hammer|wrench|club|rod|dumbbell|crowbar', re.I)
def shape_for(iid, d):
    if d['kind'] == 'firearm':
        f = d['fire']
        if not f: return 'pistol'
        cal = f.get('caliber', ''); pel = float(f.get('pellets', 1) or 1); mag = float(f.get('mag', 30) or 30)
        if pel > 1 or cal == 'SHT': return 'shotgun'
        if cal == 'SNP': return 'sniper'
        if cal == 'ARR': return 'bow'
        if cal == 'RKT': return 'launcher'
        if (cal == 'S' and mag <= 13) or (cal == 'MAG' and mag <= 8): return 'pistol'
        return 'smg' if cal == 'S' else 'rifle'
    if iid == 'bandage': return 'bandage'
    if iid == 'cash': return 'cash'
    if iid.startswith('fishing_rod'): return 'rod'
    if d['cat'] == 'Fish': return 'fish'
    if d['cat'] == 'Bait' or iid == 'earthworm': return 'bait'
    if iid == 'shovel': return 'tool'
    if d['kind'] == 'melee': return 'blunt' if BLUNT.search(d['name']) else 'melee'
    if d['kind'] == 'throwable': return 'throwable'
    if d['cat'] in CAT_SHAPE: return CAT_SHAPE[d['cat']]
    return d['kind'] if d['kind'] in masks else 'material'
def lighten(h):
    n = int(h[1:], 16)
    return '#%02x%02x%02x' % (min(255, ((n >> 16) & 255) + 70), min(255, ((n >> 8) & 255) + 70), min(255, (n & 255) + 70))
shape = {iid: shape_for(iid, d) for iid, d in items.items()}
tint = {iid: lighten(d['color']) for iid, d in items.items()}
L = ['--!nocheck', '-- GENERATED by tools/gen_icons.py from src/ui/icons.ts (masks via tools/gen_icons.mjs). Do not edit.', 'local M = {}', 'M.size = 64']
L.append('M.masks = {' + ','.join('%s=%s' % (k if k.isidentifier() else '[%s]' % luastr(k), luastr(v)) for k, v in sorted(masks.items())) + '}')
L.append('M.shape = {' + ','.join('[%s]=%s' % (luastr(k), luastr(v)) for k, v in sorted(shape.items())) + '}')
L.append('M.tint = {' + ','.join('[%s]=%s' % (luastr(k), luastr(v)) for k, v in sorted(tint.items())) + '}')
L.append('return M')
open(os.path.join(ROOT, 'src/shared/gen/Icons.luau'), 'w').write('\n'.join(L) + '\n')
from collections import Counter
print(len(items), 'items;', Counter(shape.values()).most_common(8))
