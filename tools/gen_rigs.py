"""Skeleton + clips (src/game/gz/gz_charclips.json) and exported rigs (data/rigs.json) -> Luau modules.

  python3 tools/gen_rigs.py  -> src/shared/gen/Skeleton.luau, src/shared/gen/Rigs.luau
Values stay in metres / the web frame; the client animator scales to studs.
"""
import json, sys as _sys
_sys.path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__)))
from luastr import luastr
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.dirname(ROOT)
OUT = os.path.join(ROOT, 'src/shared/gen')
os.makedirs(OUT, exist_ok=True)

def f(v, k=4):
    s = ('%.' + str(k) + 'f') % v
    s = s.rstrip('0').rstrip('.') if '.' in s else s
    return '0' if s in ('-0', '') else s

def arr(a, k=4):
    return '{' + ','.join(f(x, k) for x in a) + '}'

d = json.load(open(os.path.join(WEB, 'src/game/gz/gz_charclips.json')))
L = ['-- Generated by tools/gen_rigs.py from src/game/gz/gz_charclips.json (source skeleton + sampled clips). Do not edit.', '--!nocheck', 'local M = {}']
L.append('M.samples = %d' % d['samples'])
L.append('M.bones = {')
for b in d['bones']:
    L.append('\t{n=%s, par=%d, p=%s, r=%s},' % (json.dumps(b['n'].split('/')[-1]), b['par'] + 1 if b['par'] >= 0 else 0, arr(b['p'], 5), arr(b['r'], 5)))
L.append('}')
L.append('M.clips = {')
for name, c in d['clips'].items():
    if not c['rot']: continue
    rf = ','.join(arr(fr) for fr in c['rf'])
    pf = ','.join(arr(fr) for fr in c['pf'])
    L.append('\t[%s] = {len=%s, loop=%s, rot=%s, pos=%s, rf={%s}, pf={%s}},' % (
        json.dumps(name), f(c['len']), 'true' if c['loop'] else 'false', arr([i + 1 for i in c['rot']], 0), arr([i + 1 for i in c['pos']], 0), rf, pf))
L.append('}')
L.append('M.aim = {' + ','.join('[%d]=%s' % (int(k) + 1, arr(v, 5)) for k, v in d['aim'].items()) + '}')
L.append('M.aimPos = {' + ','.join('[%d]=%s' % (int(k) + 1, arr(v, 5)) for k, v in d['aimPos'].items()) + '}')
L.append('return M')
open(os.path.join(OUT, 'Skeleton.luau'), 'w').write('\n'.join(L) + '\n')

rigs = json.load(open(os.path.join(ROOT, 'data/rigs.json')))
R = ['-- Generated by tools/gen_rigs.py from data/rigs.json (web build rigs: beaver + Ground Zero enemies). Do not edit.', '--!nocheck', 'return {']
for key, rig in rigs.items():
    if 'error' in rig: continue
    R.append('\t[%s] = {name=%s, rootScale=%s, skeletal=%s, parts={' % (json.dumps(key), json.dumps(rig['name']), f(rig['rootScale']), 'true' if rig['skeletal'] else 'false'))
    for p in rig['parts']:
        extra = (', weapon=true' if p.get('weapon') else '') + (', head=true' if p.get('head') else '') + (', o=%s' % f(p['o'], 2) if p.get('o', 1) < 1 else '')
        R.append('\t\t{bone=%d, size=%s, p=%s, q=%s, c=%s%s},' % (p['bone'] + 1 if p['bone'] >= 0 else 0, arr(p['size']), arr(p['p']), arr(p['q'], 5), json.dumps(p['c']), extra))
    R.append('\t}},')
R.append('}')
open(os.path.join(OUT, 'Rigs.luau'), 'w').write('\n'.join(R) + '\n')
print('ok', os.path.getsize(os.path.join(OUT, 'Skeleton.luau')), os.path.getsize(os.path.join(OUT, 'Rigs.luau')))
