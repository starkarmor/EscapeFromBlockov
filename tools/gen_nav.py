"""Pack the decoded Ground Zero navmesh (src/world/gz/navmesh_ground_zero.json, AstarPath cache: verts [x, z, y] in cm,
triangle vertex indices) into src/server/gen/NavData.luau as one base64 string: int32 LE x, z, y per vertex, then
uint16 LE indices per triangle. server/Nav.luau decodes it into buffers.  Usage: python3 tools/gen_nav.py"""
import json, os, struct, base64
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.dirname(ROOT)
d = json.load(open(os.path.join(WEB, 'src/world/gz/navmesh_ground_zero.json')))
v, t = d['verts'], d['tris']
nv, nt = len(v) // 3, len(t) // 3
assert max(t) < 65536
raw = struct.pack('<%di' % len(v), *v) + struct.pack('<%dH' % len(t), *t)
b64 = base64.b64encode(raw).decode()
out = os.path.join(ROOT, 'src/server/gen/NavData.luau')
with open(out, 'w') as f:
    f.write('--!strict\n-- GENERATED by tools/gen_nav.py from src/world/gz/navmesh_ground_zero.json (%s). Do not edit.\n' % d.get('source', ''))
    f.write('return { verts = %d, tris = %d, radius = %s, data = "%s" }\n' % (nv, nt, d.get('characterRadius', 0.3), b64))
print(out, nv, nt, len(b64))
